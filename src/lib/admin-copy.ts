const variantPrefix = /^Variant (\d+) (.*)$/;

export function deskError(locale: Locale, message: string) {
  const book = locale === "fr" ? errorFr : locale === "ar" ? errorAr : null;
  if (!book) return message;
  const normalized = message.replace(/\u202f/g, " ").replace(/\u00a0/g, " ");
  if (book[normalized]) return book[normalized];
  const match = variantPrefix.exec(normalized);
  if (!match) return message;
  const detail = book[match[2]] ?? match[2];
  return locale === "ar" ? `الخيار ${match[1]} ${detail}` : `Variante ${match[1]} ${detail}`;
}

export function fillCount(template: string, count: number) {
  return template.replace("{count}", String(count));
}
